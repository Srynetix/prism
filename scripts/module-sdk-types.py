#!/usr/bin/env python3
"""The data types a module's back end shares with Prism's core, copied from the core into the
module SDK (`src-tauri/crates/module/src/types.rs`): the same names, the same JSON. The SDK is
built for WebAssembly and cannot depend on the core; this keeps them one.

    scripts/module-sdk-types.py          writes types.rs
    scripts/module-sdk-types.py --check  fails when types.rs is not what the core says (`just check`)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CORE = ROOT / "src-tauri/crates/core/src"
OUT = ROOT / "src-tauri/crates/module/src/types.rs"

# (file, items, impls kept): the types, in this order; the `impl` blocks that only use std.
SOURCES = [
    ("alerts/mod.rs", ["Severity", "AlertRule", "Notification", "OpenTarget", "FixAction", "Side", "Fix", "Alert"], ["Severity"]),
    ("state/tracker.rs", ["StatusOption"], []),
    ("changes.rs", ["ChangeEvent", "ChangeKind", "ChangeSeverity", "ChangeLink", "ChangeMr"], ["ChangeKind", "ChangeEvent"]),
    ("stages.rs", ["Stage"], []),
    ("images.rs", ["ImageTarget", "ImageTag", "ImageRef"], []),
    ("forge/mod.rs", ["Provider"], []),
    ("conventions.rs", ["Conventions"], []),
]

# What the SDK needs that the core does not derive: it reads them from Prism's JSON.
EXTRA_DERIVES = {"Conventions": ["Deserialize", "Default"], "ImageTarget": ["Serialize"], "ImageTag": ["Serialize"], "ImageRef": ["Serialize"]}
EXTRA_ATTRS = {"Conventions": ["#[serde(default)]"]}


def item(text: str, kind: str, name: str) -> str:
    """`pub struct|enum Name … }` with the doc comments and attributes above it."""
    m = re.search(rf"^pub {kind} {name}\b", text, re.M)
    if not m:
        raise SystemExit(f"{name}: not found")
    start = m.start()
    lines_before = text[:start].split("\n")[:-1]
    head = []
    for line in reversed(lines_before):
        if line.startswith("#[") or line.startswith("///") or (head and line.startswith(" ") and head[0].startswith("#[")):
            head.insert(0, line)
        else:
            break
    body_start = text.index("{", start) if text[start:].split("\n", 1)[0].rstrip().endswith("{") else None
    if body_start is None:  # a tuple or unit struct: one line
        end = text.index("\n", start)
    else:
        end = re.compile(r"^}", re.M).search(text, start).end()
    return "\n".join(head + [text[start:end]])


def impls(text: str, name: str) -> list[str]:
    out = []
    for m in re.finditer(rf"^impl {name} \{{", text, re.M):
        end = re.compile(r"^}", re.M).search(text, m.start()).end()
        out.append(text[m.start():end])
    return out


def clean(block: str, name: str) -> str:
    out = []
    for line in block.split("\n"):
        if 'cfg_attr(feature = "ts"' in line or 'cfg_attr(feature = "schema"' in line:
            continue
        line = line.replace("crate::forge::Provider", "Provider").replace("serde::Deserialize", "Deserialize").replace("serde::Serialize", "Serialize")
        m = re.match(r"^#\[derive\((.*)\)\]$", line)
        if m and name in EXTRA_DERIVES:
            derives = [d.strip() for d in m.group(1).split(",")]
            derives += [d for d in EXTRA_DERIVES[name] if d not in derives]
            line = f"#[derive({', '.join(derives)})]"
            out.append(line)
            out.extend(EXTRA_ATTRS.get(name, []))
            continue
        out.append(line)
    return "\n".join(out)


def generate() -> str:
    parts = [
        "// Generated by scripts/module-sdk-types.py from Prism's core: do not edit, run it again.",
        "//! The data a module's blocks share with Prism's core: the core's own types, the same JSON.",
        "",
        "#![allow(clippy::all)]",
        "",
        "use chrono::{DateTime, Utc};",
        "use serde::{Deserialize, Serialize};",
        "use serde_json::Value;",
        "",
    ]
    for file, names, kept in SOURCES:
        text = (CORE / file).read_text()
        for name in names:
            kind = "struct" if re.search(rf"^pub struct {name}\b", text, re.M) else "enum"
            parts.append(clean(item(text, kind, name), name))
            parts.append("")
        for name in kept:
            for block in impls(text, name):
                parts.append(clean(block, name))
                parts.append("")
    return "\n".join(parts).rstrip() + "\n"


if __name__ == "__main__":
    new = generate()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != new:
            raise SystemExit(f"{OUT.relative_to(ROOT)} is not the core's: run scripts/module-sdk-types.py")
    else:
        OUT.write_text(new)
