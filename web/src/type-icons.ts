/** A tracker's task-type icon, by its Font Awesome name; undefined when Prism has none for it. */
export function typeIcon(name: string | null | undefined): Component | undefined {
  if (!name) return undefined
  return BY_NAME[name] ?? BY_NAME[ALIASES[name] ?? '']
}
