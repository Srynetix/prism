// What `@prism/sdk` (sdk/web, the module SDK's web side) takes from Prism's window, written
// there so that a module builds with the SDK alone, without Prism's sources:
//
// - exports.json: the module contract, Prism's Svelte, the names `@prism/sdk` and
//   `@prism/sdk/words` give (web/src/modules/sdk.ts, sdk-words.ts), the Svelte modules Prism gives
//   (SVELTE_MODULES of web/src/modules/host.ts);
// - types/bindings/: the core's types `index.d.ts` names (the snapshot and what it holds);
// - package.json's `peerDependencies.svelte`: Prism's minor.
//
//   node web/scripts/module-sdk.mjs          writes them
//   node web/scripts/module-sdk.mjs --check  fails when they are not what Prism's window says (`just check`)
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const web = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const sdk = resolve(web, '../sdk/web')
const read = (p) => readFileSync(resolve(web, p), 'utf8')

/** The names a re-exporting module gives (`export { a, b as c } from …`). */
export const names = (src) => [...src.matchAll(/^export\s*\{([^}]*)\}/gm)].flatMap((m) => m[1].split(',').map((p) => p.trim().split(/\s+as\s+/).pop().trim()).filter(Boolean))

/** The core types `index.d.ts` names, and every one they import. */
const ROOTS = ['Snapshot', 'Alert', 'ArgoCd', 'ArgoApp', 'ArgoInstance', 'MergeRequest', 'Pipeline', 'Conventions', 'ForgeProvider', 'EnvironmentStage', 'ManualJob', 'PlayedJob']

function bindings() {
  const seen = new Set()
  const todo = [...ROOTS]
  while (todo.length) {
    const n = todo.pop()
    if (seen.has(n)) continue
    seen.add(n)
    for (const m of read(`src/bindings/${n}.ts`).matchAll(/from "\.\/([A-Za-z0-9_]+)"/g)) todo.push(m[1])
  }
  return [...seen].sort()
}

export function expected() {
  const contract = Number(read('src/modules/modules.svelte.ts').match(/export const CONTRACT = (\d+)/)[1])
  const svelte = JSON.parse(read('node_modules/svelte/package.json')).version
  const host = read('src/modules/host.ts')
  const block = host.slice(host.indexOf('const SVELTE_MODULES'), host.indexOf('\n}\n', host.indexOf('const SVELTE_MODULES')))
  const svelteModules = [...block.matchAll(/^\s+(?:(svelte),|'(svelte\/[^']+)':)/gm)].map((m) => m[1] ?? m[2])
  const exports = {
    contract,
    svelte,
    svelteModules,
    specifiers: { '@prism/sdk': names(read('src/modules/sdk.ts')), '@prism/sdk/words': names(read('src/modules/sdk-words.ts')) },
  }
  const files = Object.fromEntries(bindings().map((n) => [`types/bindings/${n}.ts`, read(`src/bindings/${n}.ts`)]))
  files['exports.json'] = JSON.stringify(exports, null, 2) + '\n'
  // The icons' names (`<Icon name>`), from web/src/icons.ts.
  const icons = read('src/icons.ts')
  const table = icons.slice(icons.indexOf('export const ICONS'), icons.indexOf('\n}', icons.indexOf('export const ICONS')))
  const iconNames = [...table.matchAll(/^\s+'?([a-z0-9-]+)'?:/gm)].map((m) => m[1])
  files['types/icons.d.ts'] = `// Generated by web/scripts/module-sdk.mjs from Prism's icons: do not edit.\nexport type IconName =\n${iconNames.map((n) => `  | '${n}'`).join('\n')}\n`
  const pkg = JSON.parse(readFileSync(join(sdk, 'package.json'), 'utf8'))
  pkg.peerDependencies.svelte = `~${svelte.split('.').slice(0, 2).join('.')}.0`
  files['package.json'] = JSON.stringify(pkg, null, 2) + '\n'
  return files
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const files = expected()
  const present = existsSync(join(sdk, 'types/bindings')) ? readdirSync(join(sdk, 'types/bindings')).map((f) => `types/bindings/${f}`) : []
  mkdirSync(join(sdk, 'types'), { recursive: true })
  if (process.argv.includes('--check')) {
    const wrong = Object.entries(files).filter(([p, text]) => !existsSync(join(sdk, p)) || readFileSync(join(sdk, p), 'utf8') !== text).map(([p]) => p)
    const stale = present.filter((p) => !(p in files))
    if (wrong.length || stale.length) {
      console.error(`sdk/web is not what Prism's window says (${[...wrong, ...stale].join(', ')}): run node web/scripts/module-sdk.mjs`)
      process.exit(1)
    }
  } else {
    for (const p of present.filter((p) => !(p in files))) rmSync(join(sdk, p))
    mkdirSync(join(sdk, 'types/bindings'), { recursive: true })
    for (const [p, text] of Object.entries(files)) writeFileSync(join(sdk, p), text)
  }
}
